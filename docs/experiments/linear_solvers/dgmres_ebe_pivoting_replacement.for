      subroutine lu_pp8(a, lu, ipiv, nreg, izero)
      implicit real*8 (a-h,o-z)

      real*8 a(8,8), lu(8,8)
      real*8 anorm, pmax, pivmin, tmp
      integer ipiv(8), nreg, izero
      integer i, j, k, p

      anorm = 0.0d0
      do 20 i = 1, 8
         do 10 j = 1, 8
            lu(i,j) = a(i,j)
            if (dabs(a(i,j)) .gt. anorm) anorm = dabs(a(i,j))
   10    continue
         ipiv(i) = i
   20 continue

      nreg  = 0
      izero = 0

c----- Completely empty local block: use identity preconditioner.
      if (anorm .eq. 0.0d0) then
         izero = 1
         do 40 i = 1, 8
            do 30 j = 1, 8
               lu(i,j) = 0.0d0
   30       continue
            lu(i,i) = 1.0d0
            ipiv(i) = i
   40    continue
         return
      endif

c----- Relative floor used only if partial pivoting still finds
c      a numerically vanishing pivot.
      pivmin = 1.0d-14 * anorm
      if (pivmin .lt. 1.0d-30) pivmin = 1.0d-30

      do 100 k = 1, 8

c-------- Partial pivoting: choose largest entry in column k.
         p = k
         pmax = dabs(lu(k,k))
         do 50 i = k+1, 8
            if (dabs(lu(i,k)) .gt. pmax) then
               pmax = dabs(lu(i,k))
               p = i
            endif
   50    continue
         ipiv(k) = p

c-------- Interchange complete rows.  This also correctly moves
c         previously computed L entries stored below the diagonal.
         if (p .ne. k) then
            do 60 j = 1, 8
               tmp     = lu(k,j)
               lu(k,j) = lu(p,j)
               lu(p,j) = tmp
   60       continue
         endif

c-------- Last-resort local regularization for a singular/nearly
c         singular element block after pivoting.
         if (dabs(lu(k,k)) .lt. pivmin) then
            if (lu(k,k) .lt. 0.0d0) then
               lu(k,k) = -pivmin
            else
               lu(k,k) =  pivmin
            endif
            nreg = nreg + 1
         endif

c-------- Gaussian elimination.  L and U are stored together:
c         L below the diagonal (unit diagonal), U on/above diagonal.
         if (k .lt. 8) then
            do 80 i = k+1, 8
               lu(i,k) = lu(i,k) / lu(k,k)
               do 70 j = k+1, 8
                  lu(i,j) = lu(i,j) - lu(i,k)*lu(k,j)
   70          continue
   80       continue
         endif

  100 continue

      return
      end


      subroutine element_lu_piv_all(bb, nelem, lu_el, ipiv_el,
     &                              nreg_tot, nzero_tot)
      implicit real*8 (a-h,o-z)

      integer nelem, nreg_tot, nzero_tot
      integer ipiv_el(8,nelem)
      real*8 bb(*), lu_el(8,8,nelem)
      real*8 ke(8,8)
      integer e, i, j, ik, nreg, izero

      nreg_tot  = 0
      nzero_tot = 0

      do 100 e = 1, nelem
         ik = 64*(e-1)
         do 20 i = 1, 8
            do 10 j = 1, 8
               ke(i,j) = bb(ik + (i-1)*8 + j)
   10       continue
   20    continue

         call lu_pp8(ke, lu_el(1,1,e), ipiv_el(1,e),
     &               nreg, izero)

         nreg_tot  = nreg_tot  + nreg
         nzero_tot = nzero_tot + izero
  100 continue

      return
      end


      subroutine ebe_node_weights(n, iss, nelem, wgt, iweight)
      implicit real*8 (a-h,o-z)

      integer n, nelem, iweight
      integer iss(nelem,8)
      real*8 wgt(n)
      integer i, e, a, g

      do 10 i = 1, n
         wgt(i) = 1.0d0
   10 continue

c----- iweight=0 reproduces the original unweighted additive sum.
      if (iweight .eq. 0) return

      do 20 i = 1, n
         wgt(i) = 0.0d0
   20 continue

      do 40 e = 1, nelem
         do 30 a = 1, 8
            g = iss(e,a)
            if (g .ge. 1 .and. g .le. n) wgt(g) = wgt(g)+1.0d0
   30    continue
   40 continue

c----- Partition-of-unity / multiplicity scaling.
      do 50 i = 1, n
         if (wgt(i) .gt. 0.0d0) then
            wgt(i) = 1.0d0 / wgt(i)
         else
            wgt(i) = 1.0d0
         endif
   50 continue

      return
      end


      subroutine msolve_el_piv(n, r, z, iss, nelem, lu_el,
     &                         ipiv_el, wgt)
      implicit real*8 (a-h,o-z)

      integer n, nelem
      integer iss(nelem,8), ipiv_el(8,nelem)
      real*8 r(n), z(n), lu_el(8,8,nelem), wgt(n)
      real*8 rhs(8), y(8), zloc(8), sum, tmp
      integer e, a, i, j, g, p

      do 10 i = 1, n
         z(i) = 0.0d0
   10 continue

      do 100 e = 1, nelem

c-------- Restrict global residual to one HEX8 element.
         do 20 a = 1, 8
            g = iss(e,a)
            rhs(a)  = r(g)
            y(a)    = 0.0d0
            zloc(a) = 0.0d0
   20    continue

c-------- Apply row permutations generated by partial pivoting.
         do 30 i = 1, 8
            p = ipiv_el(i,e)
            if (p .ne. i) then
               tmp    = rhs(i)
               rhs(i) = rhs(p)
               rhs(p) = tmp
            endif
   30    continue

c-------- Forward substitution: L*y = P*r_e, diag(L)=1.
         do 50 i = 1, 8
            sum = 0.0d0
            do 40 j = 1, i-1
               sum = sum + lu_el(i,j,e)*y(j)
   40       continue
            y(i) = rhs(i) - sum
   50    continue

c-------- Backward substitution: U*zloc = y.
         do 70 i = 8, 1, -1
            sum = 0.0d0
            do 60 j = i+1, 8
               sum = sum + lu_el(i,j,e)*zloc(j)
   60       continue
            zloc(i) = (y(i)-sum) / lu_el(i,i,e)
   70    continue

c-------- Add local correction to global vector.
         do 80 a = 1, 8
            g = iss(e,a)
            z(g) = z(g) + zloc(a)
   80    continue

  100 continue

c----- Optional multiplicity scaling of overlapping element updates.
      do 110 i = 1, n
         z(i) = z(i) * wgt(i)
  110 continue

      return
      end


      subroutine dgmres_ebe(n, b, x, tol, itmax, iter, err,
     &                      bb, iss, nax, nay, naz, ilosc_el)
      implicit real*8 (a-h,o-z)

      integer n, itmax, iter
      integer nax, nay, naz, ilosc_el
      integer iss((nax-1)*(nay-1)*(naz-1),8)
      real*8 tol, err, b(n), x(n), bb(*)

c----- Restarted GMRES(m).
      integer m
      parameter (m = 20)

c----- Set to 1 for multiplicity-scaled additive EBE preconditioner.
c      Set to 0 to reproduce the original unweighted summation.
      integer iweight
      parameter (iweight = 0)

c----- One combined LU matrix and one pivot vector per element.
c      This uses about half the real storage of separate L_el/U_el.
      real*8 lu_el(8,8,ilosc_el)
      integer ipiv_el(8,ilosc_el)
      real*8 wgt(n)

c----- Krylov basis and work arrays.
      real*8 v(n,m+1), z(n,m), w(n), r(n)
      real*8 h(m+1,m), cs(m), sn(m), s(m+1), y(m)

      real*8 bnrm, beta, resid, temp, denom
      real*8 wnorm0, hnext, arntol, hmax, htol
      real*8 aa, bbv
      integer i, j, k, restart, max_restart
      integer jmax, jlast, ibreak, nreg_tot, nzero_tot

c====================================================================
c     ELEMENT-BY-ELEMENT LU PRECONDITIONER WITH PARTIAL PIVOTING
c====================================================================
      call element_lu_piv_all(bb, ilosc_el, lu_el, ipiv_el,
     &                        nreg_tot, nzero_tot)

      call ebe_node_weights(n, iss, ilosc_el, wgt, iweight)

      if (nreg_tot .gt. 0) then
         write(*,'(A,I10)')
     &      'GMRES EBE: regularized local LU pivots = ', nreg_tot
      endif
      if (nzero_tot .gt. 0) then
         write(*,'(A,I10)')
     &      'GMRES EBE: zero element blocks replaced by I = ',
     &      nzero_tot
      endif

      bnrm = dnrm2(n,b)
      if (bnrm .eq. 0.0d0) bnrm = 1.0d0

      iter = 0
      err  = 1.0d0

      if (itmax .le. 0) then
         call matvec(x,r,iss,bb,nax,nay,naz)
         do 5 i = 1, n
            r(i) = b(i)-r(i)
    5    continue
         err = dnrm2(n,r)/bnrm
         return
      endif

c----- Ceiling division.  The final restart may contain fewer than m
c      iterations, so arbitrary ITMAX values are handled correctly.
      max_restart = (itmax + m - 1) / m

c====================================================================
c     RESTART LOOP
c====================================================================
      do 1000 restart = 1, max_restart

         if (iter .ge. itmax) goto 9000

c-------- True residual r = b - A*x.
         call matvec(x,r,iss,bb,nax,nay,naz)
         do 10 i = 1, n
            r(i) = b(i)-r(i)
   10    continue

         beta  = dnrm2(n,r)
         resid = beta/bnrm
         err   = resid
         if (resid .le. tol) return

c-------- Initial Arnoldi vector.
         do 20 i = 1, n
            v(i,1) = r(i)/beta
   20    continue

c-------- Initialize small GMRES arrays.
         do 40 i = 1, m+1
            s(i) = 0.0d0
            do 30 j = 1, m
               h(i,j) = 0.0d0
   30       continue
   40    continue
         do 45 i = 1, m
            y(i)  = 0.0d0
            cs(i) = 0.0d0
            sn(i) = 0.0d0
   45    continue
         s(1) = beta

         jmax = m
         if ((itmax-iter) .lt. jmax) jmax = itmax-iter
         jlast = 0

c====================================================================
c     MAIN RIGHT-PRECONDITIONED GMRES LOOP
c====================================================================
         do 200 j = 1, jmax

            iter  = iter + 1
            jlast = j
            ibreak = 0

c----------- z_j = M^{-1}*v_j.
            call msolve_el_piv(n,v(1,j),z(1,j),iss,ilosc_el,
     &                         lu_el,ipiv_el,wgt)

c----------- w = A*z_j, using the existing EBE matvec.
            call matvec(z(1,j),w,iss,bb,nax,nay,naz)
            wnorm0 = dnrm2(n,w)

c----------- Modified Gram-Schmidt Arnoldi.
            do 60 i = 1, j
               temp = 0.0d0
               do 50 k = 1, n
                  temp = temp + w(k)*v(k,i)
   50          continue
               h(i,j) = temp
               do 55 k = 1, n
                  w(k) = w(k)-temp*v(k,i)
   55          continue
   60       continue

c----------- One re-orthogonalization pass.  With m=20 the extra
c            cost is modest and substantially improves robustness.
            do 75 i = 1, j
               temp = 0.0d0
               do 65 k = 1, n
                  temp = temp + w(k)*v(k,i)
   65          continue
               h(i,j) = h(i,j)+temp
               do 70 k = 1, n
                  w(k) = w(k)-temp*v(k,i)
   70          continue
   75       continue

            hnext  = dnrm2(n,w)
            arntol = 1.0d-13*wnorm0

            if (hnext .gt. arntol) then
               h(j+1,j) = hnext
               do 80 k = 1, n
                  v(k,j+1) = w(k)/hnext
   80          continue
            else
c-------------- Happy/numerical Arnoldi breakdown.
               h(j+1,j) = 0.0d0
               ibreak = 1
               do 85 k = 1, n
                  v(k,j+1) = 0.0d0
   85          continue
            endif

c----------- Apply previous Givens rotations.
            do 90 i = 1, j-1
               temp     = cs(i)*h(i,j) + sn(i)*h(i+1,j)
               h(i+1,j) =-sn(i)*h(i,j) + cs(i)*h(i+1,j)
               h(i,j)   = temp
   90       continue

c----------- New Givens rotation, scaled to avoid overflow.
            aa  = dabs(h(j,j))
            bbv = dabs(h(j+1,j))
            if (aa .eq. 0.0d0 .and. bbv .eq. 0.0d0) then
               denom = 0.0d0
            else if (aa .ge. bbv) then
               denom = aa*dsqrt(1.0d0+(bbv/aa)*(bbv/aa))
            else
               denom = bbv*dsqrt(1.0d0+(aa/bbv)*(aa/bbv))
            endif

            if (denom .eq. 0.0d0) then
               cs(j) = 1.0d0
               sn(j) = 0.0d0
            else
               cs(j) = h(j,j)/denom
               sn(j) = h(j+1,j)/denom
            endif

            temp       = cs(j)*h(j,j)+sn(j)*h(j+1,j)
            h(j+1,j)   = 0.0d0
            h(j,j)     = temp

c----------- Update transformed right-hand side.
            temp   = cs(j)*s(j)+sn(j)*s(j+1)
            s(j+1) =-sn(j)*s(j)+cs(j)*s(j+1)
            s(j)   = temp

c----------- Cheap GMRES residual estimate.
            resid = dabs(s(j+1))/bnrm
            err   = resid

            write(*,'(A,I6,A,E12.5)')
     &         'GMRES iter=',iter,' resid=',resid

c----------- Never return here before updating x.  The old code lost
c            the last Krylov correction when ITER reached ITMAX.
            if (resid .le. tol) goto 300
            if (ibreak .ne. 0) goto 300

  200    continue

c====================================================================
c     SOLVE SMALL UPPER-TRIANGULAR SYSTEM AND UPDATE x
c====================================================================
  300    continue

c-------- Correct Krylov dimension is the number actually generated.
c         Do not infer it from s(:); s(j+1) is the residual component.
         k = jlast
         if (k .le. 0) goto 9000

c-------- Scale for detecting a rank-deficient small Hessenberg block.
         hmax = 0.0d0
         do 315 i = 1, k
            do 310 j = i, k
               if (dabs(h(i,j)) .gt. hmax) hmax = dabs(h(i,j))
  310       continue
  315    continue
         htol = 1.0d-14*hmax

         do 350 i = k, 1, -1
            temp = s(i)
            do 340 j = i+1, k
               temp = temp-h(i,j)*y(j)
  340       continue

            if (dabs(h(i,i)) .gt. htol) then
               y(i) = temp/h(i,i)
            else
c-------------- Rank-deficient reduced problem: use zero coefficient
c               and let the true residual/restart decide what follows.
               y(i) = 0.0d0
            endif
  350    continue

c-------- Right-preconditioned solution update x = x + Z*y.
         do 370 j = 1, k
            do 360 i = 1, n
               x(i) = x(i)+y(j)*z(i,j)
  360       continue
  370    continue

c-------- Always validate convergence with the true residual.
         call matvec(x,r,iss,bb,nax,nay,naz)
         do 380 i = 1, n
            r(i) = b(i)-r(i)
  380    continue

         resid = dnrm2(n,r)/bnrm
         err   = resid

         write(*,'(A,I6,A,E12.5)')
     &      'GMRES restart resid=',iter,' resid=',resid

         if (resid .le. tol) return
         if (iter .ge. itmax) goto 9000

 1000 continue

 9000 continue
      return
      end
